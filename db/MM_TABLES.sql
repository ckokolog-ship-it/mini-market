-- added after step 3a (no "add if not exists" in Oracle): the deposit already paid on a receipt,
-- the reservation of a deposit in the cash register, the deposits of a Z, and the kind DEPOSIT
declare
  procedure add_col(t varchar2, c varchar2, ddl varchar2) is
    n number;
  begin
    select count(*) into n from user_tab_cols where table_name = t and column_name = c;
    if n = 0 then
      execute immediate 'alter table ' || t || ' add (' || ddl || ')';
    end if;
  end;
begin
  add_col('MM_DOC', 'DEPOSIT', 'deposit number(12,2) default 0 not null constraint mm_doc_deposit_ck check (deposit >= 0)');
  add_col('MM_CASH_MOVE', 'RESERVATION_ID', 'reservation_id number constraint mm_cash_move_res_fk references mm_reservation');
  add_col('MM_Z', 'DEPOSITS', 'deposits number(12,2) default 0 not null');
  -- what a kind of document does (MM_BASE.sql): to the stock (STOCK_SIGN, above), to the balance of the
  -- customer or the supplier (PARTNER_SIGN: + an invoice, - a credit note, 0 a delivery note), to the
  -- VAT (VAT_SIGN: + an invoice or a receipt, - a credit note, 0 a delivery note); REF_TYPE: the kind of
  -- delivery note an invoice is made from (MM_CORE.INVOICE_FROM, ADD_NOTE). A delivery note, its invoice.
  add_col('MM_DOC_TYPE', 'PARTNER_SIGN', 'partner_sign number(1) default 0 not null '
          || 'constraint mm_doc_type_psign_ck check (partner_sign in (-1, 0, 1))');
  add_col('MM_DOC_TYPE', 'VAT_SIGN', 'vat_sign number(1) default 0 not null '
          || 'constraint mm_doc_type_vsign_ck check (vat_sign in (-1, 0, 1))');
  add_col('MM_DOC_TYPE', 'REF_TYPE', 'ref_type varchar2(3)');
  add_col('MM_DOC', 'INVOICE_ID', 'invoice_id number constraint mm_doc_invoice_fk references mm_doc');
  -- the orders (a reservation from the pages): who wrote it, when it was ready (picked), what of each
  -- line was picked
  add_col('MM_RESERVATION', 'CREATED_BY', 'created_by varchar2(30)');
  add_col('MM_RESERVATION', 'READY_AT', 'ready_at date');
  -- an order of a customer from the page of the shop (/shop/, the WiFi of the shop): SOURCE 'O' (online;
  -- 'S' the staff), the token of its page of status (not its number: not to be guessed), when the shop
  -- confirmed it (a call to the phone given)
  add_col('MM_RESERVATION', 'SOURCE', 'source varchar2(1) default ''S'' not null '
          || 'constraint mm_reservation_source_ck check (source in (''S'', ''O''))');
  add_col('MM_RESERVATION', 'PUBLIC_TOKEN', 'public_token varchar2(64) constraint mm_reservation_token_uk unique');
  add_col('MM_RESERVATION', 'CONFIRMED_AT', 'confirmed_at date');
  -- myDATA of AADE (the invoices and the credit notes of the sales, mm-api MyData.java): the kind of
  -- each document there (1.1, 5.1 ...); a document: its state (Q to be sent, S sent, E failed, X its
  -- cancellation sent), its MARK, UID and QR from AADE, the error of the last try
