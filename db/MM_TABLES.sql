-- the packs of the scratch tickets: of each one loaded, its tickets, sold and left
create or replace view mm_scratch_pack as
select g.game, substr(s.serial, 5, 7) pack, g.item_id, i.code, i.name, i.price, count(*) tickets,
       sum(case when s.status = 'S' then 1 else 0 end) sold,
       sum(case when s.status = 'A' then 1 else 0 end) left_,
       sum(case when s.status = 'X' then 1 else 0 end) returned,
       min(s.created_at) loaded_at, max(s.sold_at) last_sold
from mm_serial s
join mm_scratch_game g on g.item_id = s.item_id and g.game = substr(s.serial, 1, 4)
join mm_item i on i.id = g.item_id
where regexp_like(s.serial, '^[0-9]{14}$')
group by g.game, substr(s.serial, 5, 7), g.item_id, i.code, i.name, i.price;

-- the backup (db/backup.ps1, mm_core.backup_done): the last good one and the last failed one; STATE
-- OK, OLD (the last good one more than 2 days ago: the task of Windows stopped?), FAILED (the last
-- try failed) or NEVER; the pages of a manager show it when it is not OK
create or replace view mm_backup_state as
select ok_at, ok_file, failed_at, error, round(sysdate - ok_at, 1) days,
       case when failed_at is not null and (ok_at is null or failed_at > ok_at) then 'FAILED'
            when ok_at is null then 'NEVER'
            when sysdate - ok_at > 2 then 'OLD'
            else 'OK' end state
from (select to_date(max(case name when 'BACKUP_OK_AT' then value end), 'YYYY-MM-DD HH24:MI:SS') ok_at,
             max(case name when 'BACKUP_OK_FILE' then value end) ok_file,
             to_date(max(case name when 'BACKUP_FAILED_AT' then value end), 'YYYY-MM-DD HH24:MI:SS') failed_at,
             max(case name when 'BACKUP_ERROR' then value end) error
      from mm_setting where name like 'BACKUP\_%' escape '\');

-- the points of the retail customers: each receipt with a customer (its card scanned at the till) gives
-- POINTS_PER_EURO points for each euro of its total (MM_SETTING; 0: no points), its points used are taken
-- (each worth POINT_VALUE euros, as the discount of the receipt); a receipt cancelled, its moves back.
-- MM_CUSTOMER.POINTS is the sum of its moves (MM_CHECK)
create table if not exists mm_points (
  id          number generated by default on null as identity constraint mm_points_pk primary key,
  customer_id number        not null constraint mm_points_customer_fk references mm_customer,
  doc_id      number        constraint mm_points_doc_fk references mm_doc,
  points      number(10)    not null,
  move_at     date          default sysdate not null,
  note        varchar2(100)
);
create index if not exists mm_points_customer_ix on mm_points (customer_id, move_at);
create index if not exists mm_points_doc_ix on mm_points (doc_id);

-- FIFO (first in, first out): each move into the stock is a layer with its own cost (a receipt from a
-- supplier: the net of its line by piece; any other: that of the newest layer of the item, else the cost
-- of the item); each move out takes
-- from the oldest layers first, at their costs (MM_FIFO_OUT: what each move took, and its cost). A
-- move out with no stock left: a layer of shortage (QTY 0, LEFT_ below 0, at the cost of the newest),
-- filled by the next move in. A cancellation (a move 'Ακύρωση' of a document) gives back to the layers
-- what its line took (a sale), or takes out what is left of the layer it brought (a receipt). All of
-- it can be built again from MM_STOCK_MOVE (mm_core.fifo_rebuild); MM_CHECK: LEFT_ adds up to STOCK
create table if not exists mm_fifo (
  id          number generated by default on null as identity constraint mm_fifo_pk primary key,
  item_id     number        not null constraint mm_fifo_item_fk references mm_item,
  move_id     number,                       -- the move that brought it (MM_STOCK_MOVE)
  doc_line_id number,                       -- and its line, if of a document
  in_at       date          not null,
  qty         number(12,3)  not null,
  unit_cost   number(12,4)  not null,
  left_       number(12,3)  not null
);
create index if not exists mm_fifo_item_ix on mm_fifo (item_id, id);
create index if not exists mm_fifo_move_ix on mm_fifo (move_id);
create table if not exists mm_fifo_out (
  id          number generated by default on null as identity constraint mm_fifo_out_pk primary key,
  fifo_id     number        not null constraint mm_fifo_out_fifo_fk references mm_fifo,
  move_id     number        not null,       -- the move that took it (a cancellation: given back, below 0)
  doc_line_id number,
  qty         number(12,3)  not null,
  cost        number(14,4)  not null
);
create index if not exists mm_fifo_out_fifo_ix on mm_fifo_out (fifo_id);
create index if not exists mm_fifo_out_move_ix on mm_fifo_out (move_id);
create index if not exists mm_fifo_out_line_ix on mm_fifo_out (doc_line_id);

-- the warehouse of each move, layer, document, register (added after the warehouses came; what was
-- before them: the main one)
declare
  procedure add_col(t varchar2, c varchar2, ddl varchar2) is
    n number;
  begin
    select count(*) into n from user_tab_cols where table_name = t and column_name = c;
    if n = 0 then
      execute immediate 'alter table ' || t || ' add (' || ddl || ')';
    end if;
  end;
begin
  add_col('MM_STOCK_MOVE', 'WAREHOUSE_ID', 'warehouse_id number constraint mm_stock_move_wh_fk references mm_warehouse');
  add_col('MM_FIFO', 'WAREHOUSE_ID', 'warehouse_id number constraint mm_fifo_wh_fk references mm_warehouse');
  add_col('MM_DOC', 'WAREHOUSE_ID', 'warehouse_id number constraint mm_doc_wh_fk references mm_warehouse');
  add_col('MM_REGISTER', 'WAREHOUSE_ID', 'warehouse_id number constraint mm_register_wh_fk references mm_warehouse');
  -- a transfer between two warehouses (Δελτίο ενδοδιακίνησης, DEN: side T): the warehouse it goes to
  add_col('MM_DOC', 'TO_WAREHOUSE_ID', 'to_warehouse_id number constraint mm_doc_to_wh_fk references mm_warehouse');
  -- a count of the stock is of one warehouse (what it finds, a move there)
  add_col('MM_COUNT', 'WAREHOUSE_ID', 'warehouse_id number constraint mm_count_wh_fk references mm_warehouse');
  for c in (select search_condition_vc s from user_constraints where constraint_name = 'MM_DOC_TYPE_SIDE_CK') loop
    if instr(c.s, '''T''') = 0 then
      execute immediate 'alter table mm_doc_type drop constraint mm_doc_type_side_ck';
      execute immediate q'[alter table mm_doc_type add constraint mm_doc_type_side_ck check (side in ('S', 'P', 'T'))]';
    end if;
  end loop;
  for w in (select id from mm_warehouse where main = 'Y') loop
    execute immediate 'update mm_stock_move set warehouse_id = :w where warehouse_id is null' using w.id;
    execute immediate 'update mm_fifo set warehouse_id = :w where warehouse_id is null' using w.id;
    execute immediate 'update mm_doc set warehouse_id = :w where warehouse_id is null' using w.id;
    execute immediate 'update mm_register set warehouse_id = :w where warehouse_id is null' using w.id;
    execute immediate 'update mm_count set warehouse_id = :w where warehouse_id is null' using w.id;
  end loop;
  commit;
end;
/
create index if not exists mm_stock_move_wh_ix on mm_stock_move (item_id, warehouse_id);
create index if not exists mm_fifo_wh_ix on mm_fifo (item_id, warehouse_id, id);

-- the stock of each item in each warehouse: the sum of its moves there (MM_ITEM.STOCK: of all of them)
create or replace view mm_warehouse_stock as
select m.item_id, m.warehouse_id, w.code warehouse, w.name warehouse_name, sum(m.qty) stock
from mm_stock_move m join mm_warehouse w on w.id = m.warehouse_id
group by m.item_id, m.warehouse_id, w.code, w.name;

-- the minimum stock of an item in a branch (the main one: MM_ITEM.MIN_STOCK); below it, goods sent from
-- the central store (mm_core.transfer_missing: a draft DEN)
create table if not exists mm_warehouse_min (
  warehouse_id number      not null constraint mm_wh_min_wh_fk references mm_warehouse on delete cascade,
  item_id     number       not null constraint mm_wh_min_item_fk references mm_item on delete cascade,
  min_stock   number(12,3) not null constraint mm_wh_min_ck check (min_stock > 0),
  constraint mm_warehouse_min_pk primary key (warehouse_id, item_id)
);
create index if not exists mm_wh_min_item_ix on mm_warehouse_min (item_id);

-- the items under their minimum in each branch: what it has, what is missing, what the central store has
create or replace view mm_warehouse_min_stock as
select m.warehouse_id, w.code warehouse, w.name warehouse_name, i.id item_id, i.code, i.name, i.unit,
       nvl(s.stock, 0) stock, m.min_stock, m.min_stock - nvl(s.stock, 0) missing,
       nvl((select sum(k.qty) from mm_stock_move k join mm_warehouse c on c.id = k.warehouse_id and c.main = 'Y'
            where k.item_id = i.id), 0) central
from mm_warehouse_min m
join mm_warehouse w on w.id = m.warehouse_id and w.main = 'N' and w.active = 'Y'
join mm_item i on i.id = m.item_id and i.active = 'Y'
left join mm_warehouse_stock s on s.item_id = m.item_id and s.warehouse_id = m.warehouse_id
where nvl(s.stock, 0) < m.min_stock;

-- the check of the whole database (MM_CHECK.sql, and the tests): a row here is something that does
-- not add up. Empty: the stock is the sum of its moves, every document the sum of its lines, every
-- closed Z the sum of its documents and of its money, every receipt paid once in the register,
-- the cards in stock are their serials, the next numbers are after the last ones, the totals
-- of the months (MM_MONTHS) are their moves.
create or replace view mm_check as
select 'STOCK' what, i.id, i.code || ': ' || (i.stock + 0) || ' <> ' || nvl(m.qty, 0) detail
from mm_item i
left join (select item_id, sum(qty) qty from mm_stock_move group by item_id) m on m.item_id = i.id
where i.stock + 0 <> nvl(m.qty, 0)
union all
select 'DOC', d.id, d.doc_type || ' ' || d.doc_no || ': ' || d.total || ' <> ' || nvl(l.total, 0)
from mm_doc d
left join (select doc_id, sum(net) net, sum(vat) vat, sum(total) total from mm_doc_line group by doc_id) l
  on l.doc_id = d.id
where d.net <> nvl(l.net, 0) or d.vat <> nvl(l.vat, 0) or d.total <> nvl(l.total, 0)
union all
select 'Z', z.id, 'Z ' || z.z_no || ': ' || z.total || ' <> ' || nvl(s.total, 0)
from mm_z z
left join (select d.z_id, count(*) docs, sum(-t.stock_sign * d.total) total
           from mm_doc d join mm_doc_type t on t.code = d.doc_type
           where d.status = 'P' group by d.z_id) s on s.z_id = z.id
where z.status = 'C' and (z.total <> nvl(s.total, 0) or z.docs <> nvl(s.docs, 0))
union all
select 'Z_VAT', z.id, 'Z ' || z.z_no || ': ' || z.total || ' <> ' || nvl(v.total, 0)
from mm_z z
left join (select z_id, sum(total) total from mm_z_vat group by z_id) v on v.z_id = z.id
where z.status = 'C' and z.total <> nvl(v.total, 0)
union all
select 'Z_CASH', z.id, 'Z ' || z.z_no || ': ' || (z.cash + z.card) || ' <> ' || nvl(c.amount, 0)
from mm_z z
left join (select z_id, sum(amount) amount from mm_cash_move
           where kind in ('SALE', 'REFUND', 'DEPOSIT') group by z_id) c on c.z_id = z.id
where z.status = 'C' and z.cash + z.card <> nvl(c.amount, 0)
union all
select 'CASH', d.id, d.doc_type || ' ' || d.doc_no || ': ' || nvl(c.amount, 0)
from mm_doc d
join mm_doc_type t on t.code = d.doc_type
left join (select doc_id, sum(amount) amount from mm_cash_move
           where kind in ('SALE', 'REFUND') group by doc_id) c on c.doc_id = d.id
where d.register_id is not null and d.payment in ('CASH', 'CARD') and d.status in ('P', 'C')
  and nvl(c.amount, 0) <> case when d.status = 'C' then 0
                               else -t.stock_sign * (d.total - d.deposit) end
union all
select 'SERIAL', item_id, code || ': ' || stock || ' <> ' || available from mm_serial_check
union all
select 'WAREHOUSE', count(*), 'moves without a warehouse: ' || count(*)
from mm_stock_move where warehouse_id is null having count(*) > 0
union all
select 'FIFO_WH', nvl(m.item_id, f.item_id), nvl(m.item_id, f.item_id) || ' / ' || nvl(m.warehouse_id, f.warehouse_id)
       || ': ' || nvl(m.qty, 0) || ' <> ' || nvl(f.left_, 0)
from (select item_id, warehouse_id, sum(qty) qty from mm_stock_move group by item_id, warehouse_id) m
full join (select item_id, warehouse_id, sum(left_) left_ from mm_fifo group by item_id, warehouse_id) f
  on f.item_id = m.item_id and f.warehouse_id = m.warehouse_id
where nvl(m.qty, 0) <> nvl(f.left_, 0)
union all
select 'FIFO', i.id, i.code || ': ' || (i.stock + 0) || ' <> ' || nvl(f.left_, 0)
from mm_item i
left join (select item_id, sum(left_) left_ from mm_fifo group by item_id) f on f.item_id = i.id
where i.stock + 0 <> nvl(f.left_, 0)
union all
select 'POINTS', c.id, c.name || ': ' || c.points || ' <> ' || nvl(m.points, 0)
from mm_customer c
left join (select customer_id, sum(points) points from mm_points group by customer_id) m on m.customer_id = c.id
where c.points <> nvl(m.points, 0)
union all
select 'NEXT_NO', null, t.code || ': ' || t.next_no || ' <= ' || m.no
from mm_doc_type t
join (select doc_type, max(doc_no) no from mm_doc group by doc_type) m on m.doc_type = t.code
where t.next_no <= m.no
union all
-- the totals of the months (MM_MONTHS) are their moves
select 'ITEM_MONTH', nvl(a.item_id, b.item_id),
       to_char(nvl(a.month, b.month), 'MM/YYYY') || ': ' || nvl(a.qty_in, 0) || '/' || nvl(a.qty_out, 0)
       || ' <> ' || nvl(b.qty_in, 0) || '/' || nvl(b.qty_out, 0)
from (select item_id, month, qty_in + 0 qty_in, qty_out + 0 qty_out from mm_item_month
      where qty_in + 0 <> 0 or qty_out + 0 <> 0) a
full join (select item_id, trunc(move_at, 'MM') month, sum(case when qty > 0 then qty else 0 end) qty_in,
                  sum(case when qty < 0 then -qty else 0 end) qty_out
           from mm_stock_move group by item_id, trunc(move_at, 'MM')) b
  on b.item_id = a.item_id and b.month = a.month
where nvl(a.qty_in, 0) <> nvl(b.qty_in, 0) or nvl(a.qty_out, 0) <> nvl(b.qty_out, 0)
union all
select 'PARTNER_MONTH', nvl(a.partner_id, b.partner_id),
       nvl(a.kind, b.kind) || ' ' || to_char(nvl(a.month, b.month), 'MM/YYYY') || ': ' || nvl(a.debit, 0) || '/'
       || nvl(a.credit, 0) || ' <> ' || nvl(b.debit, 0) || '/' || nvl(b.credit, 0)
from (select * from mm_partner_month where debit <> 0 or credit <> 0) a
full join (select kind, partner_id, trunc(ldate, 'MM') month, sum(debit) debit, sum(credit) credit
           from mm_partner_event group by kind, partner_id, trunc(ldate, 'MM')) b
  on b.kind = a.kind and b.partner_id = a.partner_id and b.month = a.month
where nvl(a.debit, 0) <> nvl(b.debit, 0) or nvl(a.credit, 0) <> nvl(b.credit, 0);
