-- MM_TABLES.sql -- the tables of the mini market (Oracle 23ai/26ai).
-- Run by INSTALL.sql. "if not exists": a second run leaves the tables (and their rows) as they are.
--
-- Amounts: number(12,2) in euro. Quantities: number(12,3) (kilos too).
-- Prices of the documents: the column PRICES_INCL_VAT of MM_DOC_TYPE says whether MM_DOC_LINE.PRICE
-- includes the VAT (retail receipt) or not (invoices). NET, VAT and TOTAL of the lines and of the
-- documents are written by the package MM_CORE (step 2), the constraints keep them consistent.
-- Flags are 'Y'/'N' (not boolean): Oracle Forms reads them as plain text items.

-- VAT: the three Greek rates
create table if not exists mm_vat (
  code        varchar2(1)   constraint mm_vat_pk primary key,
  rate        number(5,2)   not null constraint mm_vat_rate_ck check (rate >= 0 and rate < 100),
  descr       varchar2(40)  not null
);

create table if not exists mm_category (
  id          number generated by default on null as identity constraint mm_category_pk primary key,
  name        varchar2(60)  not null constraint mm_category_name_uk unique
);

create table if not exists mm_item (
  id          number generated by default on null as identity constraint mm_item_pk primary key,
  code        varchar2(20)  not null constraint mm_item_code_uk unique,
  barcode     varchar2(14)  constraint mm_item_barcode_uk unique
                            constraint mm_item_barcode_ck check (regexp_like(barcode, '^([0-9]{8}|[0-9]{12,14})$')),
  name        varchar2(100) not null,
  category_id number        not null constraint mm_item_category_fk references mm_category,
  vat_code    varchar2(1)   not null constraint mm_item_vat_fk references mm_vat,
  unit        varchar2(3)   default 'PCS' not null constraint mm_item_unit_ck check (unit in ('PCS', 'KG', 'L')),
  price       number(12,2)  not null constraint mm_item_price_ck check (price >= 0),  -- retail, with VAT
  cost        number(12,4)  default 0 not null constraint mm_item_cost_ck check (cost >= 0), -- last purchase, net
  min_stock   number(12,3)  default 0 not null constraint mm_item_min_ck check (min_stock >= 0),
  stock       number(12,3)  default 0 not null,                -- the sum of MM_STOCK_MOVE (MM_CORE)
  active      varchar2(1)   default 'Y' not null constraint mm_item_active_ck check (active in ('Y', 'N'))
);
create index if not exists mm_item_category_ix on mm_item (category_id);
create index if not exists mm_item_name_ix on mm_item (upper(name));

-- customers and suppliers: the same shape. AFM: the Greek tax number, nine digits
-- (its check digit: MM_CORE.AFM_OK, step 2)
create table if not exists mm_customer (
  id          number generated by default on null as identity constraint mm_customer_pk primary key,
  name        varchar2(100) not null,
  afm         varchar2(9)   constraint mm_customer_afm_uk unique
                            constraint mm_customer_afm_ck check (regexp_like(afm, '^[0-9]{9}$')),
  doy         varchar2(60),
  address     varchar2(120),
  phone       varchar2(20),
  email       varchar2(100) constraint mm_customer_email_ck check (email like '_%@_%._%'),
  active      varchar2(1)   default 'Y' not null constraint mm_customer_active_ck check (active in ('Y', 'N'))
);

create table if not exists mm_supplier (
  id          number generated by default on null as identity constraint mm_supplier_pk primary key,
  name        varchar2(100) not null,
  afm         varchar2(9)   constraint mm_supplier_afm_uk unique
                            constraint mm_supplier_afm_ck check (regexp_like(afm, '^[0-9]{9}$')),
  doy         varchar2(60),
  address     varchar2(120),
  phone       varchar2(20),
  email       varchar2(100) constraint mm_supplier_email_ck check (email like '_%@_%._%'),
  active      varchar2(1)   default 'Y' not null constraint mm_supplier_active_ck check (active in ('Y', 'N'))
);

-- the kinds of documents: sale (S) or purchase (P), what they do to the stock (-1, 0, +1),
-- their next number
create table if not exists mm_doc_type (
  code            varchar2(3)  constraint mm_doc_type_pk primary key,
  name            varchar2(60) not null,
  side            varchar2(1)  not null constraint mm_doc_type_side_ck check (side in ('S', 'P')),
  stock_sign      number(1)    not null constraint mm_doc_type_sign_ck check (stock_sign in (-1, 0, 1)),
  prices_incl_vat varchar2(1)  not null constraint mm_doc_type_incl_ck check (prices_incl_vat in ('Y', 'N')),
  partner_needed  varchar2(1)  not null constraint mm_doc_type_partner_ck check (partner_needed in ('Y', 'N')),
  next_no         number(10)   default 1 not null constraint mm_doc_type_next_ck check (next_no >= 1)
);

-- the cash registers, their Z (one open at a time) and the money in and out
create table if not exists mm_register (
  id          number generated by default on null as identity constraint mm_register_pk primary key,
  code        varchar2(10)  not null constraint mm_register_code_uk unique,
  name        varchar2(60)  not null,
  active      varchar2(1)   default 'Y' not null constraint mm_register_active_ck check (active in ('Y', 'N'))
);

create table if not exists mm_z (
  id          number generated by default on null as identity constraint mm_z_pk primary key,
  register_id number        not null constraint mm_z_register_fk references mm_register,
  z_no        number(10)    not null,
  opened_at   date          default sysdate not null,
  closed_at   date,
  status      varchar2(1)   default 'O' not null constraint mm_z_status_ck check (status in ('O', 'C')),
  docs        number(10)    default 0 not null,
  net         number(12,2)  default 0 not null,
  vat         number(12,2)  default 0 not null,
  total       number(12,2)  default 0 not null,
  cash        number(12,2)  default 0 not null,
  card        number(12,2)  default 0 not null,
  constraint mm_z_no_uk unique (register_id, z_no),
  constraint mm_z_total_ck check (total = net + vat),
  constraint mm_z_closed_ck check ((status = 'O' and closed_at is null) or
                                   (status = 'C' and closed_at is not null and closed_at >= opened_at))
);
-- one open Z for each register
create unique index if not exists mm_z_open_uk on mm_z (case when status = 'O' then register_id end);

create table if not exists mm_z_vat (
  z_id        number        not null constraint mm_z_vat_z_fk references mm_z on delete cascade,
  vat_code    varchar2(1)   not null constraint mm_z_vat_vat_fk references mm_vat,
  net         number(12,2)  default 0 not null,
  vat         number(12,2)  default 0 not null,
  total       number(12,2)  default 0 not null,
  constraint mm_z_vat_pk primary key (z_id, vat_code),
  constraint mm_z_vat_total_ck check (total = net + vat)
);

-- the documents: D draft (no number yet, can change), P posted (numbered, stock moved), C cancelled
create table if not exists mm_doc (
  id          number generated by default on null as identity constraint mm_doc_pk primary key,
  doc_type    varchar2(3)   not null constraint mm_doc_type_fk references mm_doc_type,
  doc_no      number(10),
  doc_date    date          default trunc(sysdate) not null,
  customer_id number        constraint mm_doc_customer_fk references mm_customer,
  supplier_id number        constraint mm_doc_supplier_fk references mm_supplier,
  register_id number        constraint mm_doc_register_fk references mm_register,
  z_id        number        constraint mm_doc_z_fk references mm_z,
  status      varchar2(1)   default 'D' not null constraint mm_doc_status_ck check (status in ('D', 'P', 'C')),
  payment     varchar2(6)   default 'CASH' not null constraint mm_doc_payment_ck check (payment in ('CASH', 'CARD', 'CREDIT')),
  net         number(12,2)  default 0 not null,
  vat         number(12,2)  default 0 not null,
  total       number(12,2)  default 0 not null,
  ref_doc_id  number        constraint mm_doc_ref_fk references mm_doc,  -- a credit note: the invoice it credits
  notes       varchar2(400),
  created_at  date          default sysdate not null,
  constraint mm_doc_total_ck check (total = net + vat),
  constraint mm_doc_partner_ck check (customer_id is null or supplier_id is null),
  constraint mm_doc_no_ck check (status = 'D' or doc_no is not null)
);
-- a number once for each kind (drafts have none)
create unique index if not exists mm_doc_no_uk on mm_doc (case when doc_no is not null then doc_type end, doc_no);
create index if not exists mm_doc_date_ix on mm_doc (doc_date);
create index if not exists mm_doc_customer_ix on mm_doc (customer_id);
create index if not exists mm_doc_supplier_ix on mm_doc (supplier_id);
create index if not exists mm_doc_z_ix on mm_doc (z_id);

create table if not exists mm_doc_line (
  id          number generated by default on null as identity constraint mm_doc_line_pk primary key,
  doc_id      number        not null constraint mm_doc_line_doc_fk references mm_doc on delete cascade,
  line_no     number(5)     not null,
  item_id     number        not null constraint mm_doc_line_item_fk references mm_item,
  qty         number(12,3)  not null constraint mm_doc_line_qty_ck check (qty > 0),
  price       number(12,4)  not null constraint mm_doc_line_price_ck check (price >= 0),
  discount    number(5,2)   default 0 not null constraint mm_doc_line_disc_ck check (discount between 0 and 100),
  vat_code    varchar2(1)   not null constraint mm_doc_line_vat_fk references mm_vat,
  vat_rate    number(5,2)   not null,  -- the rate on the day of the document
  net         number(12,2)  default 0 not null,
  vat         number(12,2)  default 0 not null,
  total       number(12,2)  default 0 not null,
  constraint mm_doc_line_no_uk unique (doc_id, line_no),
  constraint mm_doc_line_total_ck check (total = net + vat)
);
create index if not exists mm_doc_line_item_ix on mm_doc_line (item_id);

-- the stock: every change of MM_ITEM.STOCK is a row here (a posted document, an adjustment,
-- the first count)
create table if not exists mm_stock_move (
  id          number generated by default on null as identity constraint mm_stock_move_pk primary key,
  item_id     number        not null constraint mm_stock_move_item_fk references mm_item,
  move_at     date          default sysdate not null,
  kind        varchar2(4)   not null constraint mm_stock_move_kind_ck check (kind in ('INIT', 'DOC', 'ADJ')),
  qty         number(12,3)  not null constraint mm_stock_move_qty_ck check (qty <> 0),
  doc_id      number        constraint mm_stock_move_doc_fk references mm_doc,
  doc_line_id number        constraint mm_stock_move_line_fk references mm_doc_line,
  note        varchar2(200),
  constraint mm_stock_move_doc_ck check ((kind = 'DOC' and doc_id is not null) or (kind <> 'DOC' and doc_id is null))
);
create index if not exists mm_stock_move_item_ix on mm_stock_move (item_id, move_at);
create index if not exists mm_stock_move_doc_ix on mm_stock_move (doc_id);

create table if not exists mm_cash_move (
  id          number generated by default on null as identity constraint mm_cash_move_pk primary key,
  register_id number        not null constraint mm_cash_move_register_fk references mm_register,
  z_id        number        not null constraint mm_cash_move_z_fk references mm_z,
  move_at     date          default sysdate not null,
  kind        varchar2(6)   not null constraint mm_cash_move_kind_ck check (kind in ('OPEN', 'IN', 'OUT', 'SALE', 'REFUND')),
  payment     varchar2(6)   default 'CASH' not null constraint mm_cash_move_payment_ck check (payment in ('CASH', 'CARD')),
  amount      number(12,2)  not null,
  doc_id      number        constraint mm_cash_move_doc_fk references mm_doc,
  note        varchar2(200)
);
create index if not exists mm_cash_move_z_ix on mm_cash_move (z_id);
