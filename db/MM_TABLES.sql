-- added after step 3a (no "add if not exists" in Oracle): the deposit already paid on a receipt,
-- the reservation of a deposit in the cash register, the deposits of a Z, and the kind DEPOSIT
declare
  procedure add_col(t varchar2, c varchar2, ddl varchar2) is
    n number;
  begin
    select count(*) into n from user_tab_cols where table_name = t and column_name = c;
    if n = 0 then
      execute immediate 'alter table ' || t || ' add (' || ddl || ')';
    end if;
  end;
begin
  add_col('MM_DOC', 'DEPOSIT', 'deposit number(12,2) default 0 not null constraint mm_doc_deposit_ck check (deposit >= 0)');
  add_col('MM_CASH_MOVE', 'RESERVATION_ID', 'reservation_id number constraint mm_cash_move_res_fk references mm_reservation');
  add_col('MM_Z', 'DEPOSITS', 'deposits number(12,2) default 0 not null');
  for c in (select data_length n from user_tab_cols where table_name = 'MM_CASH_MOVE' and column_name = 'KIND') loop
    if c.n < 10 then
      execute immediate 'alter table mm_cash_move modify (kind varchar2(10))';
    end if;
  end loop;
  for c in (select search_condition_vc s from user_constraints where constraint_name = 'MM_CASH_MOVE_KIND_CK') loop
    if instr(c.s, 'DEPOSIT') = 0 then
      execute immediate 'alter table mm_cash_move drop constraint mm_cash_move_kind_ck';
      execute immediate q'[alter table mm_cash_move add constraint mm_cash_move_kind_ck
                           check (kind in ('OPEN', 'IN', 'OUT', 'SALE', 'REFUND', 'DEPOSIT'))]';
    end if;
  end loop;
end;
/
create index if not exists mm_cash_move_res_ix on mm_cash_move (reservation_id);

-- what is reserved, and what is left: stock - the open reservations (stock + 0: ORA-55762)
create or replace view mm_item_avail as
select i.id item_id, i.code, i.name, i.stock + 0 stock,
       nvl(r.qty, 0) reserved, i.stock + 0 - nvl(r.qty, 0) available
from mm_item i
left join (select l.item_id, sum(l.qty) qty
           from mm_reservation_line l join mm_reservation r on r.id = l.reservation_id
           where r.status = 'O'
           group by l.item_id) r on r.item_id = i.id;

-- what to have ready, day by day: the open reservations by item and day of pickup
create or replace view mm_reservation_need as
select r.pickup_date, l.item_id, i.code, i.name, sum(l.qty) qty, count(*) reservations
from mm_reservation r
join mm_reservation_line l on l.reservation_id = r.id
join mm_item i on i.id = l.item_id
where r.status = 'O'
group by r.pickup_date, l.item_id, i.code, i.name;

-- baskets and sets (kits): MM_ITEM.KIT = 'Y', and what one of them has (MM_KIT_COMPONENT). Made
-- before (MM_CORE.ASSEMBLE_KIT: the components out, the kits in, moves ASM), or sold before they are
-- made: a sale takes the kits ready first, and for the rest the components themselves.
declare
  n number;
begin
  select count(*) into n from user_tab_cols where table_name = 'MM_ITEM' and column_name = 'KIT';
  if n = 0 then
    execute immediate q'[alter table mm_item add (kit varchar2(1) default 'N' not null
                         constraint mm_item_kit_ck check (kit in ('Y', 'N')))]';
  end if;
  for c in (select search_condition_vc s from user_constraints where constraint_name = 'MM_STOCK_MOVE_KIND_CK') loop
    if instr(c.s, 'ASM') = 0 then
      execute immediate 'alter table mm_stock_move drop constraint mm_stock_move_kind_ck';
      execute immediate q'[alter table mm_stock_move add constraint mm_stock_move_kind_ck
                           check (kind in ('INIT', 'DOC', 'ADJ', 'ASM'))]';
    end if;
  end loop;
end;
/

