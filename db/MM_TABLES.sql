-- an item with serials whose stock is not its cards: should stay empty
-- (stock + 0: a view may not show a reservable column as it is, ORA-55762)
create or replace view mm_serial_check as
select i.id item_id, i.code, i.stock + 0 stock,
       (select count(*) from mm_serial s where s.item_id = i.id and s.status = 'A') available
from mm_item i
where i.serial_tracked = 'Y'
  and i.stock + 0 <> (select count(*) from mm_serial s where s.item_id = i.id and s.status = 'A');

