-- promotions, applied by MM_CORE.REPRICE to every draft sale, at each change:
--   PCT     PCT % off the items or the categories of MM_PROMO_ITEM
--   NM      buy BUY_QTY, get FREE_QTY free (the cheapest pieces), any mix of its items and categories
--   BUNDLE  the items of MM_PROMO_ITEM, each QTY of it, for BUNDLE_PRICE together
-- A line takes one promotion at most: bundles first, then N+M, then the best PCT.
create table if not exists mm_promo (
  id           number generated by default on null as identity constraint mm_promo_pk primary key,
  name         varchar2(100) not null constraint mm_promo_name_uk unique,
  kind         varchar2(6)   not null constraint mm_promo_kind_ck check (kind in ('PCT', 'NM', 'BUNDLE')),
  date_from    date          not null,
  date_to      date          not null,
  active       varchar2(1)   default 'Y' not null constraint mm_promo_active_ck check (active in ('Y', 'N')),
  pct          number(5,2),
  buy_qty      number(5),
  free_qty     number(5),
  bundle_price number(12,2),
  constraint mm_promo_dates_ck check (date_to >= date_from),
  constraint mm_promo_kind_values_ck check (
    (kind = 'PCT' and pct > 0 and pct <= 100) or
    (kind = 'NM' and buy_qty >= 1 and free_qty >= 1) or
    (kind = 'BUNDLE' and bundle_price >= 0))
);
create index if not exists mm_promo_dates_ix on mm_promo (active, date_from, date_to);

create table if not exists mm_promo_item (
  id          number generated by default on null as identity constraint mm_promo_item_pk primary key,
  promo_id    number        not null constraint mm_promo_item_promo_fk references mm_promo on delete cascade,
  item_id     number        constraint mm_promo_item_item_fk references mm_item,
  category_id number        constraint mm_promo_item_cat_fk references mm_category,
  qty         number(12,3)  default 1 not null constraint mm_promo_item_qty_ck check (qty > 0),
  constraint mm_promo_item_one_ck check ((item_id is null) <> (category_id is null))
);
create index if not exists mm_promo_item_promo_ix on mm_promo_item (promo_id);
create index if not exists mm_promo_item_item_ix on mm_promo_item (item_id);
